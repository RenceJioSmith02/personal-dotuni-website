                    <h4>THE CLSU-DOTUNI STORY</h4>
                    <p>
                        <b>THE START</b>, Driven by the Higher Education Act of 1994, the CLSU-Open University was conceptualized with the drive of providing open and distance education opportunities through both degree and non-degree programs to individuals from all works of life aspiring for higher education or for improved qualifications or credentials. This act of opening the Unversity gates wider was during the insightful leadership of Dr. Fortunato A. Battad with Dr. Amor B. Monta as the main brain that birthed the concept paper titles, “<b>CLSU Open University</b>”, which was proposed ti the Board of Regents on August 29, 1997 where and when this was approved.
                        <br><br>
                        The <b>CLCU Board of Regents Resolution No. 50-97</b> institutionalized the CLSU-OU which was operationalized as a unit directly under the Office of the President of the university Dr. Flor Amor Monta as the very first Dean.
                        <br><br>
                        In 1998, the CLSU-OU initially offered two programs, Master of Science in Education and Master of Science in Rural Development. Initial students were teachers from various municipalities of Nueva Ecija and extension personnel of the Department of Agriculture. The decision to offer more degree and non-degree programs led to an increase in enrollments. 
                        <br><br>
                        In the ensuring years, demand for other degree programs led to more degree programs being offered by the CLSU-OU including PhD in Development Education and PhD in Rural Development as well as Master in Agribusiness Management, Master in Business Administration, Master in Environmental Management, Master of Science in Renewable Energy Systems and  Certificate in Teaching.
