                    <h4>THE TRANSFORMATION</h4>
                    <p>
                        At the down of the transformation and with the refinement of Dr. Monta, Dr. Ponciano Cuaresma too over as the Dean of the CLSU-OU in Januray 2017. In the international arena, the Erasmus+ Programme and the British Council amongst others have been forging linkages with different universities in the Southeast Asian Region.
                        <br><br>
                        <b>
                            THE TRANSNATIONAL HIGHER EDUCATION (TNHE)
                            <br>
                            A multi, inter and trans-disciplinary sustainable food systems education
                        </b>
                        <br><br>
                        In the international arena the Erasmis+ Programme and the British Council amongst others have been forging linkages with different universities in the Southeast Asian Region. The tie-up between CLSU and the University Liverpool, and the consequest housing of this program in the CLSU-OU led to the renaming of the CLSU-OU to DOT-Uni. With the vertical articulation of graduate courses, and the emerging need to reorient towards transnational education, CLSU-OU was transformed into <b>CLSU Distance, Open, and Transnational University (CLSU DOT-Uni)</b> on <b>February 15, 2018</b> through <b>Board of Regents Resolution No. 16-2018</b>. 
                        <br><br>
                        Parallel restructuring and reorganization commenced with a renewed purpose, aggressive institutional strengthening under the leadership of Dr. Esmeraldo M. Cabana. Connecting the DOT-Uni with the Colleges was the focus of the transformation; and structural reformation adopting stewardship under the Office of the Vice President for Academic Affairs. 
                        <br><br>
                        It os hallmarked by the strong advocacy towards connectivity and e-visibility through acquisition of Information technology equipment, shifting the gear of pedagogy towards virtual and electronic medium. In collaboration with the College of Education, management of educational materials and workshop to retool faculty tutors were held. The vision has been forced to be realized sooner than it is anticipated. When the COVID-19 pandemic disrupted the holding of residence-based courses in the university, DOT-Uni spearheaded retraining of faculty members through the Flexible Learning Workshop held in July 2020.
                    </p>
