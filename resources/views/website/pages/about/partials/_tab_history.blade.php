                    <h4>THE CONTINUUM</h4>
                    <p>
                        The vision of Dr. Cabana round its continuum in the assumption od Dr. Elaida  R. Fiegalan on Novemenber 16, 2020. The unit continue to tread its way to realize the vision of being a University of the Future.
                        <br><br>
                        Mindful of the CLSU-DOTUni horizon towards future-ready education, the unit has been highly visible in the virtual real with the current leadership seeks to pursue specific programs and prjects to follow through with the ideals not only of the distance, open and transnational mode of learning but that of the Central Luzon State University as a whole.
                        <br><br>
                        To date, CLSU-DOTUni has been highly visible to <b>17 countries</b> and catered to a total of <b>248 graduates</b> since its inception in 1998. On the 25th year of existence it is currently the virtual learning home of 227 students from around the world continually pursuing the vertical articulation o graduate courses to transnational education.  
                        <br><br>
                        Three curricular programs that are frequently requested include Diploma in Land Use Planning, Master of Science in Renewable Energy Systems, and Master in Business Administration. Other than these, the DOT-Uni is still open to offer programs that may be delivered online provided these are marketable, perceived as allied to/or is the banner program of the university, and with a Center of Development, or Center of Excellence distinction.
                        <br><br>
                        The CLSU-DOTUni horizon is dotted with the relevant restructuring approaches which the Annual Review of Curricula and Assessment Validation as the staple in the Shaping the Paradigm of a Future-ready University. It recognizes the Feedback and Use of Purposive Action Researches as the essence of CLSU’s Quality Policy Statements. It values the voices of the students providing them regular forum through “meet and greet” that respects their differing time zones. 
                        <br><br>
                        The CLSU-DOTUni keep abreast of the technology that conquers physical divide and strive to provide seamless transactions and learning environment through its incessant development of the DOT-Uni Learning Portal and related system coupled with the vision.
